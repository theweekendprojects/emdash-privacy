/**
 * Bundle the browser banner (src/client/banner.ts + @c15t/browser) into
 * dist/banner.js and dist/banner.css. Served by the plugin's public asset
 * route under a versioned, immutable-cached URL. No CDN.
 */
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { readFileSync, writeFileSync } from "node:fs";

const root = fileURLToPath(new URL("..", import.meta.url));

const result = await build({
	entryPoints: [`${root}src/client/banner.ts`],
	bundle: true,
	minify: true,
	format: "esm",
	platform: "browser",
	target: "es2022",
	outfile: `${root}dist/banner.js`,
	loader: { ".css": "css" }, // c15t css import -> dist/banner.css
	logLevel: "info",
});
if (result.errors.length) process.exit(1);

// Workers have no runtime `fs`, so the asset route cannot read dist/ files.
// Embed the built bundle as string constants the route returns directly.
const js = readFileSync(`${root}dist/banner.js`, "utf8");
let css = "";
try {
	css = readFileSync(`${root}dist/banner.css`, "utf8");
} catch {
	/* css may be inlined by the c15t entry */
}
const esc = (s) => "`" + s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";
writeFileSync(
	`${root}src/assets.generated.ts`,
	`// AUTO-GENERATED by scripts/build-client.mjs — do not edit.\n` +
		`// The browser consent bundle, embedded as strings so the plugin's asset\n` +
		`// route can serve it from a Cloudflare Worker (no runtime filesystem).\n` +
		`export const BANNER_JS = ${esc(js)};\n` +
		`export const BANNER_CSS = ${esc(css)};\n`,
);

const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0);
console.log(`banner.js  ${kb(js)} KB  (embedded in src/assets.generated.ts)`);
console.log(`banner.css ${kb(css)} KB`);
