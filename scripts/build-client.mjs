/**
 * Bundle the browser banner (src/client/banner.ts + @c15t/browser) into
 * dist/banner.js and dist/banner.css. Served by the plugin's public asset
 * route under a versioned, immutable-cached URL. No CDN.
 */
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const root = fileURLToPath(new URL("..", import.meta.url));

const result = await build({
	entryPoints: [`${root}src/client/banner.ts`],
	bundle: true,
	minify: true,
	format: "esm",
	platform: "browser",
	target: "es2022",
	outfile: `${root}dist/banner.js`,
	loader: { ".css": "css" }, // c15t css import -> dist/banner.css
	logLevel: "info",
});
if (result.errors.length) process.exit(1);

// Workers have no runtime `fs`, so the asset route cannot read dist/ files.
// Embed the built bundle as a string constant. c15t's UI renders in a shadow
// root that carries its own copy of the stylesheet (inside this bundle), so no
// page-level CSS is shipped (verified: removing it changed nothing).
const js = readFileSync(`${root}dist/banner.js`, "utf8");
const esc = (s) => "`" + s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";
writeFileSync(
	`${root}src/assets.generated.ts`,
	`// AUTO-GENERATED by scripts/build-client.mjs - do not edit.\n` +
		`// The browser consent bundle, embedded as a string so the page:fragments hook\n` +
		`// can inject it (a Cloudflare Worker has no runtime filesystem).\n` +
		`export const BANNER_JS = ${esc(js)};\n` +
		`// content hash: names the cached route, so a rebuilt bundle gets a new URL\n` +
		`export const BANNER_HASH = ${JSON.stringify(createHash("sha256").update(js).digest("hex").slice(0, 12))};\n`,
);
console.log(`banner.js  ${(Buffer.byteLength(js) / 1024).toFixed(0)} KB  (embedded in src/assets.generated.ts)`);
